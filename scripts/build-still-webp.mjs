/**
 * Build the WebP derivatives for the Work page stills, and the manifest saying
 * which ones are worth serving.
 *
 * Standard 3.0 asks for WebP with a JPEG fallback. It does not ask for a bigger
 * file, and for some frames WebP at quality 82 is bigger — high-detail stage
 * and crowd images, where JPEG's DCT does well. Those are written and then
 * discarded, and the manifest omits them so the markup falls through to JPEG.
 *
 *   node scripts/build-still-webp.mjs          # rebuild derivatives + manifest
 *   node scripts/build-still-webp.mjs --check  # fail if either is out of date
 *
 * Needs ffmpeg with libwebp on PATH, or FFMPEG_PATH pointing at one.
 */
import { execFileSync } from "node:child_process"
import { readdirSync, statSync, unlinkSync, existsSync, writeFileSync, readFileSync } from "node:fs"
import { join } from "node:path"

const DIR = "public/work/stills"
const MANIFEST = "lib/work-stills-webp.ts"
/**
 * ffmpeg is not on PATH on the build machine; it comes from the Python package
 * imageio-ffmpeg, which is what 434-context's build_media.py uses and says so in
 * its own docstring. Bare "ffmpeg" fails ENOENT here, so ask imageio-ffmpeg for
 * the binary and keep bare "ffmpeg" only as the last resort.
 */
function resolveFfmpeg() {
  if (process.env.FFMPEG_PATH) return process.env.FFMPEG_PATH
  try {
    return execFileSync("python3",
      ["-c", "import imageio_ffmpeg;print(imageio_ffmpeg.get_ffmpeg_exe())"],
      { encoding: "utf8" }).trim()
  } catch {
    return "ffmpeg"
  }
}
const FFMPEG = resolveFfmpeg()
const check = process.argv.includes("--check")

const jpgs = readdirSync(DIR).filter((f) => f.endsWith(".jpg")).sort()
const kept = []
const dropped = []

for (const jpg of jpgs) {
  const base = jpg.slice(0, -4)
  const src = join(DIR, jpg)
  const out = join(DIR, `${base}.webp`)
  if (!check || !existsSync(out)) {
    execFileSync(FFMPEG, ["-nostdin", "-y", "-v", "error", "-i", src,
      "-c:v", "libwebp", "-quality", "82", "-preset", "photo", out])
  }
  const sj = statSync(src).size
  const sw = statSync(out).size
  if (sw < sj) kept.push(base)
  else {
    dropped.push({ base, sj, sw })
    if (!check) unlinkSync(out)
  }
}

const body = `/**
 * Which stills have a WebP derivative worth serving.
 *
 * Generated by scripts/build-still-webp.mjs — do not hand-edit.
 *
 * Standard 3.0 asks for WebP with a JPEG fallback. For ${dropped.length} of the ${jpgs.length} crops
 * WebP at quality 82 came out LARGER than the JPEG, so those have no WebP and
 * fall through. Never offer the larger file.
 */
export const STILLS_WITH_WEBP: readonly string[] = [
${kept.map((k) => `  "${k}",`).join("\n")}
]
`

if (check) {
  const current = existsSync(MANIFEST) ? readFileSync(MANIFEST, "utf8") : ""
  if (current.trim() !== body.trim()) {
    console.error(`${MANIFEST} is out of date. Run: node scripts/build-still-webp.mjs`)
    process.exit(1)
  }
  console.log(`${kept.length} WebP kept, ${dropped.length} dropped — manifest current.`)
} else {
  writeFileSync(MANIFEST, body)
  console.log(`${kept.length} WebP kept, ${dropped.length} dropped (WebP larger):`)
  for (const d of dropped) console.log(`  ${d.base}  jpg=${d.sj}  webp=${d.sw}`)
}
